using System.IO;

namespace TlsCertificateLoader.Models;

/// <summary>
/// TlsCertificateLoader certificate model
/// </summary>
public struct Certificate
{
    /// <summary>
    /// Certificate constructor for Certbot file structure
    /// </summary>
    /// <param name="hostName"></param>
    /// <param name="certbotRoot"></param>
    public Certificate(string hostName, string certbotRoot)
    {
        Hostname = hostName;
        FullChainPemFilePath = Path.Combine(certbotRoot, "live", hostName, "fullchain.pem");
        PrivateKeyPemFilePath = Path.Combine(certbotRoot, "live", hostName, "privkey.pem");
    }

    /// <summary>
    /// Certificate constructor for custom file structure
    /// </summary>
    /// <param name="hostName"></param>
    /// <param name="fullChainPemFilePath"></param>
    /// <param name="privateKeyPemFilePath"></param>
    public Certificate(string hostName, string fullChainPemFilePath, string privateKeyPemFilePath)
    {
        Hostname = hostName;
        FullChainPemFilePath = fullChainPemFilePath;
        PrivateKeyPemFilePath = privateKeyPemFilePath;
    }

    /// <summary>
    /// Certificate constructor for custom file structure with password-protected private key
    /// </summary>
    /// <param name="hostName"></param>
    /// <param name="fullChainPemFilePath"></param>
    /// <param name="privateKeyPemFilePath"></param>
    /// <param name="password"></param>
    public Certificate(string hostName, string fullChainPemFilePath, string privateKeyPemFilePath, string password)
    {
        Hostname = hostName;
        FullChainPemFilePath = fullChainPemFilePath;
        PrivateKeyPemFilePath = privateKeyPemFilePath;
        Password = password;
    }

    /// <summary>
    /// Hostname associated with the certificate
    /// </summary>
    public string Hostname { get; set; }

    /// <summary>
    /// Full path to the full chain .pem file (e.g. the fullchain.pem generated by Certbot)
    /// </summary>
    public string FullChainPemFilePath { get; set; }

    /// <summary>
    /// Full path to the private key .pem file (e.g. the privkey.pem generated by Certbot)
    /// </summary>
    public string PrivateKeyPemFilePath { get; set; }

    /// <summary>
    /// Optional password used to decrypt the private key
    /// </summary>
    public string Password { get; set; } = null;
}
